#!/usr/bin/env node
/**
 * seed-synthetic.mjs - the synthetic population.
 *
 * Makes a fresh install renderable: an org, a fleet of classes, a roster, sessions against the
 * seeded templates, grades at element and competency level with repeat attempts, observable
 * behaviour selections, outcomes, frozen records from BOTH source homes, line sectors and a few
 * analysis runs.
 *
 * NO REAL PERSON AND NO REAL RECORD EVER ENTERS THIS KIT. Everything below is invented, and
 * obviously so. See docs/14_SEED_AND_SYNTHETIC_DATA.md.
 *
 * DETERMINISM. Given the same --seed, the same --as-of and the same empty database, this script
 * produces byte-identical data. Nothing calls Math.random(), Date.now() or crypto.randomUUID();
 * every draw comes from a named stream of the seeded generator, and every id comes from the
 * database's own gen_random_uuid(). --as-of is part of the contract because a window measured
 * from "today" is a different window tomorrow.
 *
 * BAND COVERAGE. The distribution is shaped to reach every band of every metric in
 * scaffold/config/analytics.yaml, including the alert half and the insufficient-data state, and
 * the run FAILS if a required band did not occur. A band that never occurs has never been seen to
 * work.
 *
 * Usage:
 *   node scripts/seed-synthetic.mjs
 *   node scripts/seed-synthetic.mjs --seed demo-2 --subjects 60 --months 36
 *   node scripts/seed-synthetic.mjs --as-of 2026-08-26 --no-commit
 */

