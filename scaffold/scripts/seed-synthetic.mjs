/** Which policy template kind each seeded template is. Codes, never names. */
const TEMPLATE_KIND_BY_CODE = new Map([
  ['SEED-SIM-REC', 'simulator_recurrent'],
  ['SEED-PROF-CHK', 'proficiency_check'],
  ['SEED-LINE-SUP', 'line_supervised'],
  ['SEED-GND-SCH', 'ground_school'],
  ['SYN-LINE-CHK', 'line_check'],
]);

/**
 * The coverage template. It exists because analytics.yaml configures an indicator scope over the
 * line_check family and the kit's four starter templates cover no such family; without it that
 * whole scope has no population and every band inside it silently fails to occur. It is published
 * through the SAME publish rules as the starter templates - there is no second door.
 */
const COVERAGE_TEMPLATE = {
  code: 'SYN-LINE-CHK',
  name: 'Line check (synthetic coverage template)',
  kind: 'line_check',
  asset_class_code: null,
  org_unit_code: null,
  version: {
    period: 'synthetic',
    change_note: 'Generated by scripts/seed-synthetic.mjs to populate the line-operations indicator scope.',
    allowed_assessor_roles: ['examiner'],
    hide_record_from_subject: false,
    setup: { rows: [{ label: 'Sector', value: '' }, { label: 'Supervision', value: '' }] },
  },
  competencies: ['KNO', 'PRO', 'COM', 'FPA', 'FPM', 'LTW', 'PSD', 'SAW', 'WLM'],
  elements: [
    { element_key: 'lc_section', catalogue_type: 'section', title: 'Line check items', position: 0, content: {} },
    ...[
      ['lc_preparation', 'Pre-flight preparation and briefing'],
      ['lc_departure', 'Departure and climb'],
      ['lc_cruise', 'Cruise and systems monitoring'],
      ['lc_communication', 'Radio communication and phraseology'],
      ['lc_threat_management', 'Threat and error management'],
      ['lc_approach', 'Approach preparation and execution'],
      ['lc_landing', 'Landing and roll-out'],
      ['lc_crew_cooperation', 'Crew cooperation and support'],
    ].map(([key, title], i) => ({
      element_key: key, catalogue_type: 'task', title, parent_key: 'lc_section',
      position: i + 1, external_ref: `SYN-C${i + 1}`,
      // NO REPEAT ATTEMPTS EXIST ON THE LINE. allow_attempts is 1 because the concept does not
      // apply, which is a different statement from "no repeats were observed".
      content: { grade_type: 'scale', allow_attempts: 1 },
    })),
  ],
};

class SeedError extends Error {}

/* ------------------------------------------------------------------------- *
 * Reading the templates back out of the database
 *
 * Deliberately NOT out of the JSON files. Element keys, attempt limits and competency ids are read
 * from the rows the template seeder actually wrote, so a grade can never reference an element key
 * that does not exist in the version it was graded against.
 * ------------------------------------------------------------------------- */
async function readTemplates(client, policy, framework) {
  const codes = [...TEMPLATE_KIND_BY_CODE.keys()];
  const { rows } = await client.query(
    `SELECT st.code, st.name, st.template_kind, stv.id AS version_id, stv.version,
            stv.hide_record_from_subject
       FROM session_templates st
       JOIN session_template_versions stv ON stv.id = st.current_version_id
      WHERE st.code = ANY($1) AND st.deleted_at IS NULL`,
    [codes],
  );
  if (rows.length === 0) {
    throw new SeedError(
      'no published templates found. Run scripts/seed-templates.mjs first: a session must name the ' +
        'template version it was graded against, and there is no such thing as a session without one.',
    );
  }
  const templates = new Map();
  for (const row of rows) {
    const policyKind = policy.template_kinds.find((k) => k.kind === TEMPLATE_KIND_BY_CODE.get(row.code));
    const { rows: elements } = await client.query(
      `SELECT element_key, element_type, is_graded, max_attempts, title, external_ref, position, content
         FROM template_elements WHERE template_version_id = $1 ORDER BY position`,
      [row.version_id],
    );
    const { rows: comps } = await client.query(
      `SELECT c.id, c.code FROM template_competencies tc
         JOIN competencies c ON c.id = tc.competency_id
        WHERE tc.template_version_id = $1 ORDER BY tc.position`,
      [row.version_id],
    );
    templates.set(row.code, {
      code: row.code,
      name: row.name,
      kind: row.template_kind,
      version: row.version,
      version_id: row.version_id,
      hide_record_from_subject: row.hide_record_from_subject,
      record_kind: policyKind?.label ?? row.template_kind,
      facility_kind: policyKind?.facility_kind ?? 'other',
      facility_label: `Demo facility ${row.template_kind}`,
      supports_attempts: policyKind?.supports_attempts === true,
      // Both of these are policy properties of the kind (config/policy.yaml section 1), carried
      // onto the template so nothing downstream has to compare template_kind against a family
      // name that the schema no longer has.
      fan_out_on_signature: policyKind?.fan_out_on_signature === true,
      one_record_per_sector: policyKind?.one_record_per_sector === true,
      elements: elements.map((e) => ({
        ...e,
        grade_type: e.content?.grade_type ?? 'scale',
      })),
      competencies: comps.map((c) => ({
        id: c.id, code: c.code, ob_ids: framework.obIdsByCompetency.get(c.id) ?? [],
      })),
    });
  }
  return templates;
}

/* ------------------------------------------------------------------------- *
 * Analysis runs
 * ------------------------------------------------------------------------- */
async function writeAnalysisRuns(client, { produced, policy, rng, configVersionId, framework }) {
  const bySubject = new Map();
  for (const item of produced) {
    if (!item.frozen) continue;
    if (!bySubject.has(item.subject.external_id)) bySubject.set(item.subject.external_id, []);
    bySubject.get(item.subject.external_id).push(item);
  }
  const candidates = [...bySubject.entries()].filter(([, items]) => items.length >= 4);
  const runRng = rng.fork('analysis');
  const chosen = runRng.sample(candidates, Math.min(
    candidates.length,
    policy.synthetic.analysis_runs.complete_count
      + policy.synthetic.analysis_runs.failed_provenance_count
      + policy.synthetic.analysis_runs.queued_count
      + policy.synthetic.analysis_runs.degraded_count,
  ));

  const counts = { complete: 0, failed: 0, queued: 0, degraded: 0 };
  const plan = [
    ...Array(policy.synthetic.analysis_runs.complete_count).fill('complete'),
    ...Array(policy.synthetic.analysis_runs.failed_provenance_count).fill('failed'),
    ...Array(policy.synthetic.analysis_runs.queued_count).fill('queued'),
    ...Array(policy.synthetic.analysis_runs.degraded_count).fill('degraded'),
  ];

  chosen.forEach(([, items], i) => {
    items.sort((a, b) => (a.plan.date < b.plan.date ? -1 : 1));
  });

  for (let i = 0; i < chosen.length; i += 1) {
    const [, items] = chosen[i];
    const kind = plan[i] ?? 'complete';
    const subjectId = items[0].subject.id;
    const grades = items.flatMap((x) => x.graded.competencies)
      .map((c) => (/^[1-5]$/.test(c.grade) ? Number(c.grade) : null))
      .filter((n) => n !== null);
    const mean = grades.reduce((a, b) => a + b, 0) / Math.max(1, grades.length);
    const belowCount = grades.filter((g) => g <= 2).length;
    const figures = {
      record_count: items.length,
      grade_count: grades.length,
      mean_grade: Number(mean.toFixed(2)),
      below_standard_count: belowCount,
      competency_means: [...new Set(items.flatMap((x) => x.graded.competencies.map((c) => c.code)))]
        .map((code) => {
          const values = items.flatMap((x) => x.graded.competencies.filter((c) => c.code === code))
            .map((c) => Number(c.grade)).filter((n) => Number.isFinite(n));
          return {
            code,
            name: framework.nameByCode.get(code),
            mean: Number((values.reduce((a, b) => a + b, 0) / Math.max(1, values.length)).toFixed(2)),
          };
        }),
    };
    const sources = items.map((x) => ({
      record_id: x.recordId, date: x.plan.date, title: x.plan.template.name,
    }));
    const concern = belowCount > 0 && grades.includes(1) ? 'high'
      : belowCount >= 2 ? 'medium' : 'low';

    if (kind === 'complete') {
      // Every number in this sentence exists in `figures`. That is not a stylistic choice: the
      // provenance gate rejects narrative whose numbers are not in the computed figure set, and
      // the gate runs BEFORE the narrative is stored.
      const narrative = `<p>Reviewed ${figures.record_count} records covering ${figures.grade_count} `
        + `competency grades. The mean competency grade is ${figures.mean_grade}, with `
        + `${figures.below_standard_count} grades below the standard.</p>`;
      await client.query(
        `INSERT INTO analysis_runs (person_id, framework_id, run_kind, status, completed_at,
                                    config_version_id, concern_level, figures, narrative_html,
                                    narrative_model, sources)
         VALUES ($1,$2,'subject','complete', now(), $3,$4,$5,$6,'demo-model-fast',$7)`,
        [subjectId, framework.id, configVersionId, concern, JSON.stringify(figures), narrative,
         JSON.stringify(sources)],
      );
      counts.complete += 1;
    } else if (kind === 'failed') {
      // DELIBERATELY REJECTED. The model wrote a figure that the deterministic core never
      // computed, the gate caught it, and the narrative was NOT stored. A fresh install therefore
      // contains a worked example of the gate doing its job, which is the only way anyone ever
      // finds out whether it does.
      await client.query(
        `INSERT INTO analysis_runs (person_id, framework_id, run_kind, status, completed_at,
                                    config_version_id, concern_level, figures, narrative_html,
                                    narrative_model, sources, error)
         VALUES ($1,$2,'subject','failed', now(), $3,$4,$5,NULL,'demo-model-deep',$6,$7)`,
        [subjectId, framework.id, configVersionId, concern, JSON.stringify(figures),
         JSON.stringify(sources),
         'provenance gate rejected the narrative before storage: 2 of 7 numbers in the generated '
         + 'prose are absent from the computed figure set (an invented mean and an invented record '
         + 'count). The prose was discarded; the figures below are unaffected because they were '
         + 'computed in SQL and never passed through the model.'],
      );
      counts.failed += 1;
    } else if (kind === 'queued') {
      await client.query(
        `INSERT INTO analysis_runs (person_id, framework_id, run_kind, status, config_version_id)
         VALUES ($1,$2,'subject','queued',$3)`,
        [subjectId, framework.id, configVersionId],
      );
      counts.queued += 1;
    } else {
      // Degraded mode: no inference endpoint configured. Every figure still computes; only the
      // prose is absent. This is a SUPPORTED state and a fresh install should contain one.
      await client.query(
        `INSERT INTO analysis_runs (person_id, framework_id, run_kind, status, completed_at,
                                    config_version_id, concern_level, figures, narrative_html,
                                    narrative_model, sources)
         VALUES ($1,$2,'subject','complete', now(), $3,$4,$5,NULL,NULL,$6)`,
        [subjectId, framework.id, configVersionId, concern,
         JSON.stringify({ ...figures, degraded_mode: true }), JSON.stringify(sources)],
      );
      counts.degraded += 1;
    }
  }
  return counts;
}

/* ------------------------------------------------------------------------- *
 * Main
 * ------------------------------------------------------------------------- */
async function main() {
  const policyFile = await loadPolicy();
  const policy = policyFile.data;
  const syn = policy.synthetic;

  const seedText = argValue('--seed', syn.default_seed);
  const subjectCount = Number(argValue('--subjects', syn.default_subjects));
  const monthsRequested = Number(argValue('--months', syn.default_months));
  const asOf = parseDate(argValue('--as-of', new Date().toISOString().slice(0, 10)));
  const noCommit = argFlag('--no-commit');
  const rng = makeRng(seedText, 'root');

  const client = await connect();
  try {
    await client.query('BEGIN');

    // ORDER MATTERS AND IT IS ASSERTED HERE. Thresholds come from analytics_config, which
    // load-analytics-config.mjs fills after migrating. Reading them first is what makes a
    // threshold-dependent seed impossible to run against defaults.
    const analytics = await readAnalyticsConfig(client);

    const { rows: existing } = await client.query(
      "SELECT count(*)::int AS n FROM people WHERE external_id LIKE $1",
      [`${syn.person_id_prefix}%`],
    );
    if (existing[0].n > 0 && !argFlag('--allow-existing')) {
      throw new SeedError(
        `${existing[0].n} synthetic people already exist. This generator is not incremental: soft ` +
          'deletion is enforced by trigger everywhere, so there is no honest way to remove a ' +
          'previous population in place. Drop the database and run scripts/reset-to-seed.mjs.',
      );
    }

    const framework = await readFrameworkFromDb(client);
    const { rows: fwMeta } = await client.query(
      'SELECT id, code FROM competency_frameworks WHERE is_active LIMIT 1',
    );
    framework.id = fwMeta[0].id;
    framework.code = fwMeta[0].code;
    const { rows: compRows } = await client.query(
      'SELECT id, code, name FROM competencies WHERE framework_id = $1', [framework.id],
    );
    framework.nameByCode = new Map(compRows.map((c) => [c.code, c.name]));
    const { rows: obRows } = await client.query(
      'SELECT id, competency_id FROM observable_behaviours WHERE framework_id = $1 ORDER BY position',
      [framework.id],
    );
    framework.obIdsByCompetency = new Map();
    for (const ob of obRows) {
      if (!framework.obIdsByCompetency.has(ob.competency_id)) {
        framework.obIdsByCompetency.set(ob.competency_id, []);
      }
      framework.obIdsByCompetency.get(ob.competency_id).push(ob.id);
    }

    // The coverage template, through the shared publish path.
    const today = isoDate(new Date());
    const coverageErrors = validateTemplate(COVERAGE_TEMPLATE, {
      policy, competencyCodes: new Set(framework.competencyIdByCode.keys()),
      obCodes: new Set(framework.obIdByCode.keys()), today, effectiveFrom: today,
    });
    if (coverageErrors.length > 0) {
      throw new SeedError(`the coverage template fails the publish rules: ${coverageErrors[0]}`);
    }
    await publishDefinition(client, { file: '(generated)', definition: COVERAGE_TEMPLATE }, {
      policy, framework, effectiveFrom: today,
      allowedKinds: await allowedTemplateKinds(client),
      allowedElementTypes: await allowedCheckValues(client, 'template_elements', 'element_type'),
    });

    const templates = await readTemplates(client, policy, framework);

    // --- the window ------------------------------------------------------
    const scopes = analytics.json('program_indicator.scopes');
    const requiredFrom = [
      ...Object.values(scopes).map((s) => s.base_from),
      analytics.text('control_chart.estimation_start'),
    ].filter(Boolean).sort()[0];
    const requestedStart = addMonths(asOf, -monthsRequested);
    const windowStart = syn.extend_window_to_cover_analytics_bases
      && parseDate(requiredFrom) < requestedStart ? parseDate(requiredFrom) : requestedStart;

    const months = [];
    for (let cursor = new Date(Date.UTC(windowStart.getUTCFullYear(), windowStart.getUTCMonth(), 1));
         cursor <= asOf; cursor = addMonths(cursor, 1)) {
      months.push(monthKey(cursor));
    }
    const baseTo = Object.values(scopes).map((s) => s.base_to).filter(Boolean).sort().slice(-1)[0];
    const { schedule, quiet, quarterSchedule, quarterKinds } = buildDifficultySchedule({
      months, baseTo, quietCount: syn.volume.quiet_period_months, scopes,
    });

    const cfg = {
      windowYears: months.length / 12,
      configVersion: analytics.version,
      belowStandardMax: analytics.int('grade_scale.below_standard_max'),
      criticalGrade: analytics.int('grade_scale.critical_grade'),
      nonScoring: analytics.json('grade_scale.non_scoring'),
      booleanValues: policy.grading.boolean_grade_values,
      seatRoles: policy.seats.subject_roles,
      nonScoringShare: syn.volume.non_scoring_share,
      obSelectionShare: syn.volume.ob_selection_share,
      remarkShareLowGrades: syn.volume.remark_share_low_grades,
      justificationGradeMax: analytics.int('assessor_fairness.justification.grade_max'),
      minNRate: analytics.int('suppression.min_n_rate'),
      minNComparisonSide: analytics.int('suppression.min_n_comparison_side'),
      sci: {
        window: analytics.int('screening_index.window_sessions'),
        minValid: analytics.int('screening_index.min_valid_grades'),
        halfLife: analytics.num('screening_index.recency_half_life'),
        points: analytics.json('screening_index.points'),
        cleanRunN: analytics.int('screening_index.clean_run_n'),
        cleanRunMinGrade: analytics.int('screening_index.clean_run_min_grade'),
        amberBelow: analytics.num('screening_index.bands.amber_below'),
        aboveOver: analytics.num('screening_index.bands.above_over'),
      },
      concern: {
        highGrade1AtLeast: analytics.int('concern.high.grade_1_count_at_least'),
        mediumGrade2AtLeast: analytics.int('concern.medium.grade_2_count_at_least'),
        lowMinObservations: analytics.int('concern.low.min_observations'),
      },
      flagged: {
        grade1AtLeast: analytics.int('flagged_record.grade_1_at_least'),
        grade2AtLeast: analytics.int('flagged_record.grade_2_at_least'),
      },
      trend: {
        flatBand: analytics.num('trend.flat_band'),
        minPoints: analytics.int('trend.min_points'),
      },
      coverage: {
        competencyCoverageMin: analytics.num('coverage.targets.competency_coverage_min'),
        obCoverageMin: analytics.num('coverage.targets.ob_coverage_min'),
        remarkCoverageMin: analytics.num('coverage.targets.remark_coverage_min'),
      },
      scopes,
      alertSigma: analytics.json('program_indicator.alert_sigma'),
      targetType: analytics.text('program_indicator.target.type'),
      targetValue: analytics.num('program_indicator.target.value'),
      statusRules: {
        consecutiveAboveTarget: analytics.int('program_indicator.status_rules.consecutive_above_target'),
        consecutiveAtAlert1: analytics.int('program_indicator.status_rules.consecutive_at_alert1'),
      },
      assessor: {
        minRecordsBanded: analytics.int('assessor_fairness.adjusted_delta.min_records_banded'),
        kShrink: analytics.num('assessor_fairness.adjusted_delta.k_shrink'),
        outlierAbs: analytics.num('assessor_fairness.adjusted_delta.outlier_abs'),
        sigmaMin: analytics.num('assessor_fairness.spread.sigma_min'),
        sigmaFloor: analytics.num('assessor_fairness.spread.sigma_floor'),
        justificationGradeMax: analytics.int('assessor_fairness.justification.grade_max'),
        justificationMinWords: analytics.int('assessor_fairness.justification.min_words'),
      },
    };

    // --- build and write --------------------------------------------------
    const population = buildPopulation({ policy, rng, subjectCount });
    // Each subject carries a fixed aptitude offset, so the same person is consistently the same
    // person across every session rather than a fresh draw each time.
    const aptitudeRng = rng.fork('aptitude');
    for (const subject of population.subjects) {
      subject.aptitude = aptitudeRng.normal(0, 0.25);
      // Repeat eligibility is a property of the SUBJECT, decided once. Deciding it per element
      // gives nearly every subject a repeat over a two-year window, which is not a minority.
      subject.repeatEligible = subject.profile.alwaysRepeat === true
        || aptitudeRng.chance(syn.volume.repeat_attempt_share);
    }

    const { orgIdByCode, assetIdByCode, users, staffUsers } =
      await writePopulation(client, population, { policy, asOf });

    const plans = buildSchedule({
      policy, rng, population, templates, months, quiet, schedule, quarterSchedule, quarterKinds, cfg,
    });
    const { counts, produced } = await writePlans(client, plans, {
      framework, cfg, rng, population, orgIdByCode, assetIdByCode,
    });

    const policyConfigId = await recordConfigVersion(client, {
      name: 'policy', version: policy.version, checksum: policyFile.checksum,
      payload: policy, notes: 'Loaded by scripts/seed-synthetic.mjs.',
    });
    const { rows: analyticsVersion } = await client.query(
      "SELECT id FROM config_versions WHERE name = 'analytics' AND is_active LIMIT 1",
    );
    const configVersionId = analyticsVersion[0]?.id ?? policyConfigId;
    if (!analyticsVersion[0]) {
      console.warn(
        '[warn] no active analytics config_versions row; analysis runs are stamped with the policy ' +
        'version instead. scripts/load-analytics-config.mjs should record one.',
      );
    }

    const runCounts = await writeAnalysisRuns(client, {
      produced, policy, rng, configVersionId, framework,
    });

    // --- coverage ---------------------------------------------------------
    const coverage = assessCoverage({ produced, population, cfg });
    const missing = coverage.rows.filter((r) => r.required && !r.ok);

    console.log('\nBAND COVERAGE');
    console.log(renderTable(
      ['metric', 'band', 'ok', 'detail'],
      coverage.rows.map((r) => [r.metric, r.band, r.ok ? 'yes' : (r.required ? 'NO' : 'n/a'), r.detail]),
    ));
    for (const entry of syn.not_covered ?? []) {
      console.log(`\nnot covered by this layer: ${entry.key}\n  ${entry.reason}`);
    }

    console.log('\nSYNTHETIC POPULATION');
    console.log(renderTable(['item', 'count'], [
      ['seed', seedText],
      ['as of', isoDate(asOf)],
      ['window', `${months[0]} .. ${months[months.length - 1]} (${months.length} months)`],
      ['window extended to cover base windows', windowStart < requestedStart ? `yes, from ${requiredFrom}` : 'no'],
      ['analytics config version', analytics.version],
      ['org units', population.orgUnits.length],
      ['asset classes', population.assetClasses.length],
      ['people', population.people.length],
      ['  subjects', population.subjects.length],
      ['  assessors', population.assessors.length],
      ['users', users.length],
      ['  staff role accounts', staffUsers.length],
      ['templates used', templates.size],
      ['sessions', counts.sessions],
      ['  open (in progress)', counts.sessionsOpen],
      ['  void', counts.sessionsVoid],
      ['session subjects graded', counts.subjects],
      ['element grades', counts.elementGrades],
      ['  repeat attempts', counts.repeats],
      ['  non-scoring (NR/NO/NA)', counts.nonScoring],
      ['competency grades', counts.competencyGrades],
      ['observable behaviour selections', counts.obSelections],
      ['records', counts.records],
      ['  source app', counts.recordsApp],
      ['  source import', counts.recordsImport],
      ['record tasks', counts.recordTasks],
      ['record competencies', counts.recordCompetencies],
      ['line sectors', counts.sectors],
      ['analysis runs complete', runCounts.complete],
      ['analysis runs rejected by provenance gate', runCounts.failed],
      ['analysis runs queued', runCounts.queued],
      ['analysis runs degraded (no narrative)', runCounts.degraded],
      ['quiet months (suppressed periods)', quiet.size],
    ]));

    if (missing.length > 0) {
      console.error('\nBANDS THAT DID NOT OCCUR:');
      for (const row of missing) console.error(`  ${row.metric} / ${row.band} (${row.detail})`);
      throw new SeedError(
        `${missing.length} required band(s) were not produced. A band that never occurs has never ` +
          'been seen to work, so the run is rejected rather than committed. Adjust the profiles in ' +
          'scripts/synthetic/population.mjs or the difficulty schedule in synthetic/events.mjs.',
      );
    }

    if (noCommit) {
      await client.query('ROLLBACK');
      console.log('\n--no-commit: everything above was generated and rolled back.');
    } else {
      await client.query('COMMIT');
      console.log('\nCommitted.');

      // ANALYZE, and it is not housekeeping. A freshly seeded database has NO STATISTICS: every
      // table was empty when the planner last looked, autovacuum has not been round yet, and the
      // planner therefore estimates one row for everything. The estimate does not make a query
      // wrong, it makes it choose a nested loop where it wanted a hash join - and a view that
      // re-evaluates an eight-second subquery once per outer row takes minutes instead of
      // seconds. On this kit's own population that is the difference between av_assessor_adjusted
      // answering in 1.8 seconds and not answering inside forty. The install then looks broken in
      // a way that points at the analytics layer rather than at the statistics, which is where
      // the time goes.
      const analyzeStarted = Date.now();
      await client.query('ANALYZE');
      console.log(`Statistics collected (ANALYZE, ${Date.now() - analyzeStarted}ms). `
        + 'A freshly seeded database has none, and every plan built without them is built for a '
        + 'one-row table.');
    }
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  if (err instanceof SeedError) console.error(`\nsynthetic seed REJECTED: ${err.message}\n`);
  else console.error(err);
  process.exit(1);
});
